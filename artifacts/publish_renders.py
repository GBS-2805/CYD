#!/usr/bin/env python3
"""Build the bundle that puts the app's renders at public https addresses.

CONVENTIONS.md asks for a labelled link to every touched screen before a UI change
ships, and a chat client cannot open a file in this workspace. So the frames that git
already holds are copied, unchanged, into `artifacts/site/public/` with a gallery page,
and that folder is deployed as a static site. Nothing here draws anything: the pixels
are `artifacts/renders/`'s, and `check_renders.py` is what keeps those honest.

    python3 artifacts/publish_renders.py          # rebuild the bundle
    npx wrangler ...                              # or: sites_deploy with manifest.json

`public/` is build output and is ignored by git; the frames beside it are the source.
"""
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
RENDERS = HERE / "renders"
PUBLIC = HERE / "site" / "public"

# Every frame the capture writes, in the order a person reads the app.
SCREENS = [
    ("home", "The drawer", "PAIRED, BOARDS, SERIAL, and the owner's mark"),
    ("home-open", "BOARDS expanded", "the boards that hold projects, one row each"),
    ("projects", "The shelf", "alphabetical, folded, with the libraries note first"),
    ("projects-open", "One project open", "its notes, log, deck block and actions"),
    ("paired", "The link", "telemetry, the deck card, what is advertising, saved decks"),
    ("serial", "USB", "the flasher, its three retries, the monitor"),
    ("settings", "Settings", "permissions, the allowlist, the bridge"),
]

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Off-site — the app, screen by screen</title>
<style>
  :root {{ --field: #3f4e96; --band: #d9d9d9; --ink: #000000;
           --on: #d9d9d9; --dim: rgba(217,217,217,.70); --rule: rgba(217,217,217,.26); }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--field); color: var(--on);
          font: 16px/1.6 "DejaVu Sans Mono", ui-monospace, Menlo, Consolas, monospace; }}
  header {{ background: var(--band); color: var(--ink); padding: 22px 20px; }}
  header h1 {{ margin: 0; font-size: 20px; letter-spacing: .02em; }}
  header p {{ margin: 4px 0 0; font-size: 13px; color: rgba(0,0,0,.6); }}
  main {{ padding: 24px 20px 60px; }}
  figure {{ margin: 0 0 34px; }}
  figcaption {{ font-size: 13px; color: var(--dim); padding-top: 8px; }}
  figcaption b {{ color: var(--on); }}
  img {{ display: block; width: 100%; max-width: {maxw}px; height: auto;
         border: 1px solid var(--rule); }}
  .note {{ border-top: 1px solid var(--rule); padding-top: 14px; font-size: 12px;
           color: var(--dim); }}
</style>
</head>
<body>
<header>
  <h1>Off-site — the app, screen by screen</h1>
  <p>captures of the app's own views, drawn by Android's renderer</p>
</header>
<main>
{figures}
  <p class="note">These are captures, not device screenshots: `CaptureTest` builds the
  app's real views and draws them on a JVM, so a padding or a row height is the app's
  own arithmetic. Frames come from `artifacts/renders/`; this page is generated by
  `artifacts/publish_renders.py`.</p>
</main>
</body>
</html>
"""


def main():
    PUBLIC.mkdir(parents=True, exist_ok=True)
    for stale in PUBLIC.glob("*.png"):
        stale.unlink()

    figures = []
    widest = 0
    for name, title, blurb in SCREENS:
        source = RENDERS / (name + ".png")
        if not source.is_file():
            raise SystemExit("missing %s: run android-companion/capture.sh first" % source)
        shutil.copyfile(source, PUBLIC / source.name)
        widest = max(widest, source.stat().st_size and 0)
        figures.append(
            '  <figure>\n    <img src="%s.png" alt="%s">\n'
            '    <figcaption><b>%s</b> &middot; %s</figcaption>\n  </figure>'
            % (name, title, title, blurb))

    sheet = RENDERS / "chat-sheet.jpg"
    if sheet.is_file():
        shutil.copyfile(sheet, PUBLIC / sheet.name)
        figures.append(
            '  <figure>\n    <img src="%s" alt="all seven screens side by side">\n'
            '    <figcaption><b>All seven</b> &middot; one strip, for a message</figcaption>\n'
            '  </figure>' % sheet.name)

    (PUBLIC / "index.html").write_text(
        PAGE.format(figures="\n".join(figures), maxw=520))

    files = sorted(p.name for p in PUBLIC.iterdir())
    print("bundle: %d files in %s" % (len(files), PUBLIC.relative_to(HERE.parent)))
    for name in files:
        print("  %-20s %6.0f kB" % (name, (PUBLIC / name).stat().st_size / 1024))


if __name__ == "__main__":
    main()
