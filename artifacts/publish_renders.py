#!/usr/bin/env python3
"""Build the bundle that puts the app's renders at public https addresses.

CONVENTIONS.md asks for a labelled link to every touched screen before a UI change
ships, and a chat client cannot open a file in this workspace. So the frames that git
already holds are copied, unchanged, into `artifacts/site/public/` with a gallery page,
and that folder is deployed as a static site. Nothing here draws anything: the pixels
are `artifacts/renders/`'s, and `check_renders.py` is what keeps those honest.

The gallery is a **scroll**, not a contact sheet: one screen under the next at phone
width, separated by a hairline and one line of caption, so opening it and dragging down
walks the app from the front page to settings. A strip of nine thumbnails shows the
shape of the app and nothing readable; this shows what the phone shows.

The strip is the one exception, because a single chat message wants one picture. It is
drawn here from the same nine frames the page uses, so it cannot be the seven-frame
strip an earlier capture left in `renders/` while the app grew two screens.

    python3 artifacts/publish_renders.py          # rebuild the bundle
    # then deploy artifacts/site/manifest.json with the sites tooling

`public/` is build output and is ignored by git; the frames beside it are the source.
"""
import shutil
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
RENDERS = HERE / "renders"
PUBLIC = HERE / "site" / "public"

# Every frame the capture writes, in the order a person meets them in the app.
SCREENS = [
    ("home", "The drawer", "PAIRED, BOARDS, SERIAL, and the owner's mark"),
    ("home-open", "BOARDS expanded", "the boards that hold projects, one row each"),
    ("projects", "The shelf", "alphabetical, folded, with the libraries note first"),
    ("projects-open", "One project open", "its notes, log, deck block and actions"),
    ("projects-edit", "Adding a project",
     "the form the shelf opens: name, tagline, status, notes, DELETE"),
    ("projects-file", "Attaching a file",
     "the picker as a card: every sketch and image FILES holds, one tap each"),
    ("paired", "The link", "telemetry, the deck card, what is advertising, saved decks"),
    ("serial", "USB", "the flasher, its three retries, the monitor"),
    ("settings", "Settings", "permissions, the allowlist, the bridge"),
]

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Off-site — the app, scrolling</title>
<style>
  :root {{
    --field: #000000; --band: #e4e3de; --ink: #000000;
    --on: #f1f0eb; --dim: rgba(241, 240, 235, .70); --rule: rgba(241, 240, 235, .23);
  }}
  * {{ box-sizing: border-box; }}
  body {{
    margin: 0; background: var(--field); color: var(--on);
    font: 15px/1.55 "DejaVu Sans Mono", ui-monospace, SFMono-Regular, Menlo,
          Consolas, monospace;
  }}
  header {{
    position: sticky; top: 0; z-index: 2; background: var(--band); color: var(--ink);
    padding: 14px 18px; border-bottom: 1px solid rgba(0, 0, 0, .14);
  }}
  header h1 {{ margin: 0; font-size: 15px; letter-spacing: .01em; font-weight: 600; }}
  header p {{ margin: 3px 0 0; font-size: 12px; color: rgba(0, 0, 0, .58); }}
  main {{ max-width: 420px; margin: 0 auto; }}
  figure {{ margin: 0; }}
  figure img {{ display: block; width: 100%; height: auto; }}
  figcaption {{
    padding: 10px 18px 16px; font-size: 12px; color: var(--dim);
    border-bottom: 1px solid var(--rule);
  }}
  figcaption b {{ color: var(--on); font-weight: 400; }}
  figcaption span {{ display: block; color: var(--dim); }}
  footer {{
    padding: 18px 18px 48px; font-size: 12px; color: var(--dim);
    border-top: 1px solid var(--rule);
  }}
</style>
</head>
<body>
<header>
  <h1>Off-site — the app, scrolling</h1>
  <p>drag down: front page to settings, one screen at a time</p>
</header>
<main>
{figures}
  <footer>
    Captures of the app's own views, drawn by Android's renderer on a JVM — not device
    screenshots, so a padding or a row height here is the app's own arithmetic. The
    frames are <code>artifacts/renders/</code>'s; this page is generated by
    <code>artifacts/publish_renders.py</code>, and <code>check_renders.py</code> fails
    when a committed frame stops matching what the app draws.
  </footer>
</main>
</body>
</html>
"""


# The strip one chat message shows. Drawn from the same nine frames the page uses, at
# publish time: a strip copied out of `renders/` is how the published one came to show
# the seven frames of an earlier capture a week after the app had grown two more.
STRIP = "chat-sheet.jpg"
THUMB = 196                          # a 393 px capture at half width
GUTTER = 10
PAD = 12
FIELD = (0x3F, 0x4E, 0x96)           # Palette.FIELD, the page's own ground
BAND = (0xD9, 0xD9, 0xD9)            # Palette.BAND, the hairline the app draws


def strip():
    """One row of the nine screens, drawn from the frames just copied into `public/`.

    The page is a scroll because nine screens side by side are unreadable at phone
    width; this is those same nine as one picture, so it is drawn rather than carried
    in `renders/`, where a copy dates while the app moves. The frames keep their own
    proportions and hang from the same top edge, so a short screen is a short card.
    """
    shots = []
    for name, _, _ in SCREENS:
        frame = Image.open(PUBLIC / (name + ".png")).convert("RGB")
        shots.append(frame.resize((THUMB, round(frame.height * THUMB / frame.width)),
                                  Image.LANCZOS))
    cell = max(shot.height for shot in shots)
    width = PAD * 2 + THUMB * len(shots) + GUTTER * (len(shots) - 1)
    canvas = Image.new("RGB", (width, cell + PAD * 2), FIELD)
    draw = ImageDraw.Draw(canvas)
    x = PAD
    for shot in shots:
        canvas.paste(shot, (x, PAD))
        draw.rectangle([x - 1, PAD - 1, x + THUMB, PAD + shot.height], outline=BAND)
        x += THUMB + GUTTER
    canvas.save(PUBLIC / STRIP, quality=88, optimize=True)
    return canvas.size


def main():
    PUBLIC.mkdir(parents=True, exist_ok=True)
    for stale in PUBLIC.glob("*.png"):
        stale.unlink()

    figures = []
    for name, title, blurb in SCREENS:
        source = RENDERS / (name + ".png")
        if not source.is_file():
            raise SystemExit("missing %s: run android-companion/capture.sh first" % source)
        shutil.copyfile(source, PUBLIC / source.name)
        figures.append(
            '  <figure>\n    <img src="%s.png" alt="%s">\n'
            '    <figcaption><b>%s</b><span>%s</span></figcaption>\n  </figure>'
            % (name, title, title, blurb))

    size = strip()

    # The logo sheet is drawn by `logo_icon.py` beside the drawable it shows, so it
    # cannot describe a mark the app stopped drawing. Copied here, not remembered.
    logo = HERE / "logo-compare.png"
    if logo.is_file():
        shutil.copyfile(logo, PUBLIC / logo.name)

    (PUBLIC / "index.html").write_text(PAGE.format(figures="\n".join(figures)))

    files = sorted(p.name for p in PUBLIC.iterdir())
    print("bundle: %d files in %s" % (len(files), PUBLIC.relative_to(HERE.parent)))
    for name in files:
        print("  %-20s %6.0f kB" % (name, (PUBLIC / name).stat().st_size / 1024))
    print("strip: %s %d x %d from the same %d frames" % (STRIP, size[0], size[1],
                                                         len(SCREENS)))


if __name__ == "__main__":
    main()
